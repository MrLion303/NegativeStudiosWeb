-- Ejecutar en Supabase SQL Editor para activar likes en respuestas del foro.
create table if not exists public.forum_post_comment_likes (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.forum_post_comments(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique(comment_id, user_id)
);
create index if not exists forum_post_comment_likes_user_idx on public.forum_post_comment_likes(user_id, created_at desc);
alter table public.forum_post_comment_likes enable row level security;
drop policy if exists "Forum reply hearts are publicly readable" on public.forum_post_comment_likes;
create policy "Forum reply hearts are publicly readable" on public.forum_post_comment_likes for select using(true);
drop policy if exists "Users can add their own forum reply hearts" on public.forum_post_comment_likes;
create policy "Users can add their own forum reply hearts" on public.forum_post_comment_likes for insert to authenticated with check(user_id=(select auth.uid()));
drop policy if exists "Users can remove their own forum reply hearts" on public.forum_post_comment_likes;
create policy "Users can remove their own forum reply hearts" on public.forum_post_comment_likes for delete to authenticated using(user_id=(select auth.uid()));
grant select on public.forum_post_comment_likes to anon, authenticated;
revoke insert on public.forum_post_comment_likes from authenticated;
grant insert (comment_id, user_id) on public.forum_post_comment_likes to authenticated;
grant delete on public.forum_post_comment_likes to authenticated;

-- Evita que borrar una respuesta propia elimine también respuestas de otros usuarios.
create or replace function public.protect_foreign_forum_replies()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if auth.uid() is not null
    and not exists(select 1 from public.profile_badges where user_id=auth.uid() and is_mod=true)
    and exists(
      with recursive descendants(id,user_id) as (
        select c.id,c.user_id from public.forum_post_comments c where c.parent_comment_id=old.id
        union all
        select c.id,c.user_id from public.forum_post_comments c join descendants d on c.parent_comment_id=d.id
      )
      select 1 from descendants where user_id <> auth.uid()
    )
  then
    raise exception 'No puedes eliminar una respuesta que contiene respuestas de otros usuarios. Un moderador puede hacerlo.' using errcode='42501';
  end if;
  return old;
end;
$$;
drop trigger if exists protect_foreign_forum_replies on public.forum_post_comments;
create trigger protect_foreign_forum_replies before delete on public.forum_post_comments
for each row execute function public.protect_foreign_forum_replies();
